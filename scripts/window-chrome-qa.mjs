import { _electron as electron } from 'playwright';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..');
await mkdir(path.join(root, 'output/test-data'), { recursive: true });
const work = await mkdtemp(path.join(root, 'output/test-data/window-chrome-'));
const env = { ...process.env, SOCIAL_COPY_DATA_DIRECTORY: path.join(work, 'profile') }; delete env.ELECTRON_RUN_AS_NODE;
let app, page;
const checks = [], errors = [];
const pass = name => { checks.push(name); console.log('PASS', name); };
async function launch() {
  app = await electron.launch({ executablePath: path.join(root, 'out/SocialCopyStudio-win32-x64/SocialCopyStudio.exe'), env });
  page = await app.firstWindow(); page.setDefaultTimeout(20000); page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: '我的草稿', exact: true }).waitFor();
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.webContents.setBackgroundThrottling(false); w.hide(); });
}
const mainState = () => app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; return { maximized: w.isMaximized(), minimized: w.isMinimized(), bounds: w.getBounds(), content: w.getContentBounds() }; });
try {
  await launch();
  const frame = await mainState(); assert.ok(Math.abs(frame.content.y - frame.bounds.y) <= 8);
  assert.equal(await page.locator('.window-controls button').count(), 3);
  const dragRegion = await page.locator('.window-drag-region').boundingBox(); assert.ok(dragRegion.width > 100 && dragRegion.height >= 40);
  assert.equal(await page.locator('.window-drag-region').evaluate(el => getComputedStyle(el).getPropertyValue('-webkit-app-region')), 'drag');
  assert.equal(await page.locator('.window-controls button').first().evaluate(el => getComputedStyle(el).getPropertyValue('-webkit-app-region')), 'no-drag');
  await page.getByRole('button', { name: '最大化窗口', exact: true }).click();
  await page.getByRole('button', { name: '还原窗口', exact: true }).waitFor(); assert.equal((await mainState()).maximized, true);
  await page.getByRole('button', { name: '还原窗口', exact: true }).click();
  await page.getByRole('button', { name: '最大化窗口', exact: true }).waitFor(); assert.equal((await mainState()).maximized, false);
  await page.getByRole('button', { name: '最小化窗口', exact: true }).click(); assert.equal((await mainState()).minimized, true);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].restore());
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].maximize());
  await page.getByRole('button', { name: '还原窗口', exact: true }).waitFor();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].unmaximize());
  await page.getByRole('button', { name: '最大化窗口', exact: true }).waitFor();
  pass('Custom controls perform minimize/maximize/restore and reflect native state changes');
  const invalidRejected = await page.evaluate(async () => { try { await window.desktop.windowAction('not-allowed'); return false; } catch { return true; } });
  assert.equal(invalidRejected, true); pass('Window IPC rejects unknown commands');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].showInactive());
  await page.screenshot({ path: path.join(work, 'custom-frame.png') });
  await page.getByRole('button', { name: '新建草稿', exact: true }).click();
  await page.getByRole('region', { name: '预览工作台', exact: true }).waitFor();
  const id = await page.evaluate(async () => (await window.desktop.listDrafts()).drafts[0].id);
  await page.locator('.wechat-proof__add').click();
  const picker = page.getByRole('dialog', { name: '添加图片', exact: true }); await picker.waitFor();
  assert.equal(await page.locator('.titlebar-page-actions').evaluate(el => el.inert), true);
  const titlebar = await page.locator('.custom-titlebar').boundingBox(), overlay = await page.locator('.modal-backdrop').boundingBox();
  assert.ok(overlay.y >= titlebar.y + titlebar.height - 1);
  await page.getByRole('button', { name: '最大化窗口', exact: true }).click();
  await page.getByRole('button', { name: '还原窗口', exact: true }).click();
  await picker.getByRole('button', { name: '返回上一层', exact: true }).click();
  assert.equal(await page.locator('.titlebar-page-actions').evaluate(el => el.inert), false);
  pass('Modal blocks page navigation while retaining window controls');
  await app.evaluate((_electron, draftId) => {
    const fs = process.getBuiltinModule('node:fs').promises;
    globalThis.originalRename = fs.rename;
    fs.rename = async (from, to) => { if (String(to).endsWith(draftId + '.json')) throw Object.assign(new Error('模拟磁盘不足'), { code: 'ENOSPC' }); return globalThis.originalRename(from, to); };
  }, id);
  await page.getByRole('textbox', { name: '发布文案', exact: true }).fill('保存失败时应保留窗口');
  await page.getByRole('button', { name: '关闭窗口', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '草稿未保存，已保留窗口' }).waitFor();
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().length), 1);
  await app.evaluate(() => { process.getBuiltinModule('node:fs').promises.rename = globalThis.originalRename; });
  await page.getByRole('button', { name: '关闭提示', exact: true }).click();
  pass('Failed draft save prevents the custom close button from destroying the window');
  const caption = '自定义窗体关闭保存 🌊\n内容完整保留';
  await page.getByRole('textbox', { name: '发布文案', exact: true }).fill(caption);
  await page.getByRole('button', { name: '导出素材包', exact: true }).click();
  await page.getByRole('dialog', { name: '导出发布素材包', exact: true }).waitFor();
  const closed = app.waitForEvent('close', { timeout: 20000 });
  await page.getByRole('button', { name: '关闭窗口', exact: true }).click().catch(error => { if (!String(error).includes('closed')) throw error; });
  await closed; app = null;
  assert.equal(JSON.parse(await readFile(path.join(work, 'profile/library/drafts', id + '.json'), 'utf8')).caption, caption);
  await launch(); await page.locator(`[data-draft-id="${id}"] .library-card-open`).click();
  assert.equal(await page.getByRole('textbox', { name: '发布文案', exact: true }).inputValue(), caption);
  pass('Custom close saves pending edits even with a modal open; restart restores the caption');
  assert.deepEqual(errors, []);
  await writeFile(path.join(work, 'verification.json'), JSON.stringify({ version: '0.3.11', checks, rendererErrors: errors, nativeDragAndSnap: 'not automated; drag/no-drag regions checked' }, null, 2));
} finally { if (app) await app.close().catch(() => {}); console.log('Test materials retained:', work); }
